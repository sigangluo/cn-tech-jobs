"""城市 -> 国家/地区。

官网自带国家字段的公司直接用官网的；没有的靠城市推断：这里只列**海外**城市，表里没有的一律算中国
（国内公司的职位绝大多数在国内，国内城市和省份名太多，不值得逐个列）。
新增公司后如果出现了新的海外城市，补到 OVERSEAS 里即可，不用改别的地方。
"""

# 港澳台和官网一致，归在「中国」下，所以不列在这里
OVERSEAS = {
    "新加坡": "新加坡",
    "吉隆坡": "马来西亚", "亚罗牙也": "马来西亚",
    "雅加达": "印度尼西亚", "普哇加达县": "印度尼西亚",
    "马尼拉": "菲律宾", "胡志明": "越南", "曼谷": "泰国",
    "东京": "日本", "首尔": "韩国",
    "班加罗尔": "印度", "迪拜": "阿联酋",
    "悉尼": "澳大利亚",
    "伦敦": "英国", "慕尼黑": "德国", "格拉茨": "奥地利", "马德里": "西班牙",
    "美国": "美国", "旧金山": "美国", "西雅图": "美国", "森尼韦尔": "美国", "圣何塞": "美国",
    "San Jose(USA)": "美国", "帕罗奥多": "美国",
    "多伦多": "加拿大", "圣保罗": "巴西",
}
DEFAULT_COUNTRY = "中国"


def countries_of(job):
    """一个职位涉及的国家/地区列表（去重，保持顺序）。官网给了国家就用官网的，否则按城市推断。"""
    if job.get("country"):
        return [job["country"]]
    out = []
    for c in job["cities"] or [""]:
        k = OVERSEAS.get(c, DEFAULT_COUNTRY)
        if k not in out:
            out.append(k)
    return out
